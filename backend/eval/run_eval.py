"""Speech evaluation on Gnani Prisma (STT) and Timbre (TTS), using synthetic audio only.

    uv run python eval/run_eval.py languages   # per-language TTS -> STT round trip of the safety lines
    uv run python eval/run_eval.py noise       # triage cases at 16 kHz, 8 kHz telephony, and 8 kHz + noise

All "patient" audio is generated by Timbre from the labelled sentences in triage_cases.yaml,
so no real voices or recordings are involved. Noise is synthetic (pink noise, mains hum and
babble made from other synthetic utterances). Results go to eval/out/. Needs GNANI_API_KEY.
TTS audio is cached in eval/out/audio to save credits.
"""

import argparse
import hashlib
import io
import json
import sys
import time
import unicodedata
import wave
from pathlib import Path

import numpy as np
import soxr
import yaml

from careloop.config import settings
from careloop.languages import LANGUAGES, LINES, voice_for
from careloop.models import Urgency
from careloop.triage import max_level, scan_utterance

HERE = Path(__file__).parent
OUT = HERE / "out"
AUDIO = OUT / "audio"
RATE = 16000
rng = np.random.default_rng(7)


def tts(text: str, language: str) -> np.ndarray:
    from gnani.tts.client import AudioConfig, GnaniTTSClient

    key = hashlib.sha1(f"{language}|{text}".encode()).hexdigest()[:16]
    path = AUDIO / f"{key}.wav"
    if not path.exists():
        client = GnaniTTSClient(settings.gnani_api_key)
        data = client.synthesize(
            text, voice=voice_for(language), model=settings.tts_model, language=language,
            audio_config=AudioConfig(sample_rate=RATE, container="wav"),
        )
        path.write_bytes(data)
    with wave.open(str(path)) as w:
        pcm = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
        if w.getframerate() != RATE:
            pcm = soxr.resample(pcm, w.getframerate(), RATE)
    return pcm


def to_wav(pcm: np.ndarray, rate: int) -> bytes:
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes((np.clip(pcm, -1, 1) * 32767).astype(np.int16).tobytes())
    return buf.getvalue()


def telephony(pcm: np.ndarray) -> np.ndarray:
    """Band-limit to a narrowband phone channel (8 kHz, ~300-3400 Hz)."""
    narrow = soxr.resample(pcm, RATE, 8000)
    spec = np.fft.rfft(narrow)
    freqs = np.fft.rfftfreq(len(narrow), 1 / 8000)
    spec[(freqs < 300) | (freqs > 3400)] = 0
    return np.fft.irfft(spec, n=len(narrow)).astype(np.float32)


def pink_noise(n: int) -> np.ndarray:
    white = rng.standard_normal(n)
    spec = np.fft.rfft(white)
    spec /= np.sqrt(np.maximum(np.arange(len(spec)), 1))
    noise = np.fft.irfft(spec, n=n)
    return (noise / np.abs(noise).max()).astype(np.float32)


def add_noise(signal: np.ndarray, snr_db: float, babble: np.ndarray, rate: int) -> np.ndarray:
    n = len(signal)
    t = np.arange(n) / rate
    hum = 0.3 * np.sin(2 * np.pi * 50 * t)
    bab = np.resize(babble, n) if len(babble) else np.zeros(n)
    noise = pink_noise(n) + hum + 0.8 * bab
    p_sig = np.mean(signal**2) + 1e-12
    p_noise = np.mean(noise**2) + 1e-12
    noise *= np.sqrt(p_sig / (p_noise * 10 ** (snr_db / 10)))
    return (signal + noise).astype(np.float32)


def stt(wav: bytes, language: str) -> tuple[str, float]:
    from gnani.stt.client import GnaniSTTClient

    client = GnaniSTTClient(settings.gnani_api_key)
    for attempt in range(3):
        start = time.perf_counter()
        try:
            result = client.transcribe_bytes(wav, language_code=language, format="transcribe")
            return (result.get("transcript") or "").strip(), (time.perf_counter() - start) * 1000
        except Exception as e:  # Prisma REST sometimes returns a gateway 504; retry before giving up.
            if attempt == 2 or "50" not in str(e)[:12]:
                raise
            time.sleep(2 * (attempt + 1))
    raise RuntimeError("unreachable")


def cer(ref: str, hyp: str, native_only: bool = False) -> float:
    """Character error rate. native_only drops Latin letters, so an English name in an Indic
    line ("Asha", "Dr. Rao") that Prisma correctly writes in native script isn't counted as an error."""
    def keep(c: str) -> bool:
        return c.isalnum() and not (native_only and c.isascii() and c.isalpha())

    a = "".join(c for c in unicodedata.normalize("NFC", ref.lower()) if keep(c))
    b = "".join(c for c in unicodedata.normalize("NFC", hyp.lower()) if keep(c))
    if not a:
        return 0.0
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1] / len(a)


def cmd_languages() -> list[dict]:
    rows = []
    for code in LANGUAGES:
        for key in ("consent", "emergency"):
            text = LINES[code][key].format(name="Asha", clinic="Demo Clinic", doctor="Dr. Rao")
            try:
                pcm = tts(text, code)
            except Exception as e:  # keep going; record the failure in the matrix
                rows.append({"language": code, "line": key, "tts_ok": False, "stt_ok": False, "error": f"TTS: {str(e)[:200]}"})
                print(rows[-1], file=sys.stderr)
                continue
            try:
                hyp, ms = stt(to_wav(pcm, RATE), code)
                rows.append({"language": code, "line": key, "tts_ok": True, "stt_ok": True,
                             "cer": round(cer(text, hyp, native_only=code != "en-IN"), 3),
                             "stt_ms": round(ms), "hypothesis": hyp})
            except Exception as e:
                rows.append({"language": code, "line": key, "tts_ok": True, "stt_ok": False, "error": f"STT: {str(e)[:200]}"})
            print(rows[-1], file=sys.stderr)
    return rows


def cmd_noise() -> list[dict]:
    cases = yaml.safe_load((HERE / "triage_cases.yaml").read_text())
    clean = {i: tts(c["text"], c["lang"]) for i, c in enumerate(cases)}
    rows = []
    for i, case in enumerate(cases):
        # Babble from three other synthetic utterances.
        others = [clean[j] for j in rng.choice([k for k in clean if k != i], size=3, replace=False)]
        babble16 = sum(np.resize(o, len(clean[i])) for o in others) / 3
        phone = telephony(clean[i])
        babble8 = telephony(babble16)
        variants = {
            "clean_16k": (clean[i], RATE),
            "phone_8k": (phone, 8000),
            "phone_8k_snr10": (add_noise(phone, 10, babble8, 8000), 8000),
            "phone_8k_snr5": (add_noise(phone, 5, babble8, 8000), 8000),
        }
        expected = Urgency.parse(case["expect"])
        for name, (pcm, rate) in variants.items():
            hyp, ms = stt(to_wav(pcm, rate), case["lang"])
            got = max_level(scan_utterance(hyp))
            rows.append({
                "lang": case["lang"], "text": case["text"], "variant": name, "hypothesis": hyp,
                "cer": round(cer(case["text"], hyp), 3), "expected": expected.name, "got": got.name,
                "triage_ok": got == expected, "missed_emergency": expected == Urgency.EMERGENCY and got < Urgency.EMERGENCY,
                "stt_ms": round(ms),
            })
            print(f"{case['lang']} {name:16} cer={rows[-1]['cer']:.2f} {got.name:9} {'ok' if got == expected else 'MISS'}", file=sys.stderr)
    return rows


def summarise_noise(rows: list[dict]) -> str:
    lines = ["| Variant | Mean CER | Triage accuracy | Missed emergencies | Median STT ms |", "|---|---|---|---|---|"]
    for v in ("clean_16k", "phone_8k", "phone_8k_snr10", "phone_8k_snr5"):
        rs = [r for r in rows if r["variant"] == v]
        if not rs:
            continue
        lines.append(
            f"| {v} | {np.mean([r['cer'] for r in rs]):.3f} | {np.mean([r['triage_ok'] for r in rs]):.0%} | "
            f"{sum(r['missed_emergency'] for r in rs)} / {sum(r['expected'] == 'EMERGENCY' for r in rs)} | "
            f"{int(np.median([r['stt_ms'] for r in rs]))} |"
        )
    return "\n".join(lines)


def summarise_languages(rows: list[dict]) -> str:
    lines = ["| Language | Consent line CER | Emergency line CER | Timbre TTS | Prisma STT |", "|---|---|---|---|---|"]
    for code, lang in LANGUAGES.items():
        rs = {r["line"]: r for r in rows if r["language"] == code}
        c, e = rs.get("consent", {}), rs.get("emergency", {})
        tts_ok = c.get("tts_ok") and e.get("tts_ok")
        stt_ok = c.get("stt_ok") and e.get("stt_ok")
        lines.append(f"| {lang.english_name} ({code}) | {c.get('cer', '—')} | {e.get('cer', '—')} | "
                     f"{'ok' if tts_ok else 'failed'} | {'ok' if stt_ok else 'failed'} |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("what", choices=["languages", "noise"])
    args = parser.parse_args()
    if not settings.gnani_api_key:
        sys.exit("Set GNANI_API_KEY first.")
    AUDIO.mkdir(parents=True, exist_ok=True)
    rows = cmd_languages() if args.what == "languages" else cmd_noise()
    (OUT / f"{args.what}.json").write_text(json.dumps(rows, ensure_ascii=False, indent=2))
    table = summarise_languages(rows) if args.what == "languages" else summarise_noise(rows)
    (OUT / f"{args.what}.md").write_text(table + "\n")
    print(table)


if __name__ == "__main__":
    main()
